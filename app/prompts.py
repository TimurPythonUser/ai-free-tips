def build_merge_prompt(blocks: list[dict], posted_titles: list[str] | None = None) -> str:
    """blocks: [{"label": str, "text": str, "sources": [ {url,title,date}, ... ]}]
    posted_titles: заголовки халяв, УЖЕ опубликованных в канале (для антиповтора).
    Возвращает промпт РЕДАКТОРУ: собрать сухие факты (не посты)."""
    def fmt_sources(sources: list[dict]) -> str:
        lines = []
        for s in sources:
            if not s.get("url"):
                continue
            date = s.get("date") or "дата?"
            title = s.get("title") or ""
            lines.append(f"- [{date}] {title} — {s['url']}")
        return "\n".join(lines) or "(нет)"

    parts = []
    if posted_titles:
        parts.append("⛔️ УЖЕ ОПУБЛИКОВАНО В КАНАЛЕ — НЕ ВКЛЮЧАЙ ЭТИ ХАЛЯВЫ ПОВТОРНО.")
        parts.append("Даже если та же халява попалась с ДРУГОГО сайта/источника, с другим заголовком "
                     "или чуть другой датой — это ТОТ ЖЕ факт, его брать НЕЛЬЗЯ. Смотри на СУТЬ "
                     "(какой сервис + что дают), а не на формулировку. Список уже вышедшего:")
        for t in posted_titles:
            parts.append(f"  ✗ {t}")
        parts.append("")
    parts += ["Вот результаты нескольких поисков халяв из мира ИИ.",
              "Каждый источник помечен датой публикации в квадратных скобках — ИСПОЛЬЗУЙ эти даты.\n"]
    for i, b in enumerate(blocks, 1):
        parts.append(f"=== ПОИСК {i} ({b.get('label', '')}) ===")
        parts.append("Текст:")
        parts.append(b.get("text", "") or "(пусто)")
        parts.append("\nИсточники (формат: [дата] заголовок — ссылка):")
        parts.append(fmt_sources(b.get("sources", [])))
        parts.append("")
    head = "\n".join(parts)

    return head + """
=== ЗАДАЧА ===
Собери из ВСЕХ поисков выше список конкретных ХАЛЯВ из мира ИИ как СУХИЕ ФАКТЫ.
НЕ пиши рекламные посты, НЕ придумывай завлекающие заголовки — только факты. Правила:
1. Включай конкретные ХАЛЯВЫ, АКЦИИ и НОВИНКИ-с-бесплатным: бесплатный доступ/тариф, промокод,
   бесплатные кредиты, превью или ранний доступ к платному, бесплатный инструмент, скидка/распродажа,
   грант, промо-акция, гивэвей, конкурс/хакатон с призами, бета-доступ с бонусом, реферальный бонус,
   бесплатный курс, а также новые ИИ-сервисы/модели, которые на старте дают что-то бесплатно.
   Должно быть КОНКРЕТНОЕ предложение с выгодой, а не просто новость/обзор без халявы.
2. РАЗНООБРАЗИЕ ОБЯЗАТЕЛЬНО. Подборка НЕ должна быть про одну тему или одну технологию.
   Максимум ОДИН пункт на одну и ту же тему/технологию/продукт. Охвати разные категории:
   доступ к чат-ботам/LLM, генерация картинок, видео, музыка/голос, кодинг, API-кредиты,
   превью моделей и т.д. Если в результатах много про одно и то же — возьми лучшее одно.
3. ССЫЛКА: сильно предпочитай ПРЯМУЮ страницу самого сервиса/акции/оффера (где халяву реально
   забирают), а НЕ новостную статью про неё. Если среди источников есть и офиц. страница сервиса,
   и новость — бери страницу сервиса. Если есть ТОЛЬКО новостная статья — используй её (система
   пометит ссылку как «источник», и пост честно об этом скажет). Бери точные URL из источников
   выше, ничего не выдумывай. Ссылка обязательна.
4. ДАТА обязательна и берётся из пометки [дата] у источника (формат YYYY-MM-DD).
   Пункты, для которых нет достоверной даты, помечай date=null — они пойдут в конец.
5. Убери дубликаты (одна и та же акция из разных поисков — один пункт). И НИКОГДА не включай
   халяву, которая есть в списке «⛔️ УЖЕ ОПУБЛИКОВАНО» выше — даже с другого источника/заголовка.
6. Все текстовые поля — на русском языке.
7. Отсортируй по дате: самые свежие — первыми.
8. Верни от 8 до 15 РАЗНОТЕМНЫХ пунктов, если материала хватает.
9. Для каждого пункта — ТОЛЬКО факты (без рекламы):
   - title: короткое ФАКТИЧЕСКОЕ название халявы (что это), без эмодзи и сленга.
   - what: что КОНКРЕТНО дают бесплатно — лимиты, кредиты, срок, условия. 1-2 фразы фактов.
   - url: прямая ссылка (обязательна).
   - date: "YYYY-MM-DD" из пометки источника или null.
   - source: название сервиса/сайта.
   - category: одна из — chatbot, image, video, audio, code, api, course, other.
   - has_mcp: true/false — просто пометка, на порядок НЕ влияет.

Ответ — СТРОГО JSON-объект вида:
{
  "items": [
    {
      "title": "Фактическое название халявы",
      "what": "Что конкретно дают: лимиты/кредиты/срок/условия",
      "url": "https://прямая-ссылка",
      "date": "YYYY-MM-DD или null",
      "source": "название сервиса",
      "category": "chatbot|image|video|audio|code|api|course|other",
      "has_mcp": true/false
    }
  ]
}
Никакого текста вне JSON."""
