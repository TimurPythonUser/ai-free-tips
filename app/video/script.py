_STYLES = {"classic": _SYSTEM, "howto": _SYSTEM_HOWTO}


def _parse_json_object(text: str) -> dict:
    """Достаём JSON-объект из ответа модели (с ```json``` или без)."""
    text = (text or "").strip()
    m = re.search(r"```(?:json)?\s*(.*?)```", text, re.S)
    if m:
        text = m.group(1).strip()
    s, e = text.find("{"), text.rfind("}")
    if s != -1 and e != -1 and e > s:
        try:
            data = json.loads(text[s:e + 1])
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return {}


def narration_text(script: dict) -> str:
    """Полный текст озвучки из сценария (хук + фразы + CTA)."""
    parts = [script.get("hook", "")] + list(script.get("phrases") or []) + [script.get("cta", "")]
    return " ".join(p.strip().rstrip(".") + "." for p in parts if (p or "").strip())


async def _ask(system: str, fact: str) -> dict | None:
    """Общий вызов сценариста с ретраем на кривой JSON."""
    for attempt in (1, 2):
        raw = await clients.deepseek(
            [{"role": "system", "content": system},
             {"role": "user", "content": fact}],
            temperature=config.VIDEO_SCRIPT_TEMPERATURE,
            model=config.CREATIVE_MODEL,
        )
        script = _parse_json_object(raw)
        if script.get("hook") and script.get("phrases") and script.get("cta"):
            return script
        await bus.log(f"      ⚠ сценарист вернул кривой JSON (попытка {attempt}/2)", "warn")
    return None


async def write_script(item: dict, style: str = "classic") -> dict | None:
    """Сценарий по одной халяве. style: classic | howto («разбор за 3 шага»)."""
    fact = "\n".join(filter(None, [
        f"Название: {item.get('title', '')}",
        f"Суть: {item.get('what') or item.get('benefit') or item.get('description') or ''}",
        f"Текст поста: {item.get('text') or item.get('text_body') or ''}",
        f"Ссылка (для понимания контекста, в ролик не вставлять): {item.get('url', '')}",
    ]))
    return await _ask(_STYLES.get(style, _SYSTEM), fact)


async def write_top3(items: list[dict]) -> dict | None:
    """Сценарий-дайджест «топ-3 халявы недели» по трём халявам."""
    blocks = []
    for i, it in enumerate(items, 1):
        text = re.sub(r"<[^>]+>", "", (it.get("text") or it.get("text_body") or ""))[:300]
        blocks.append(f"ХАЛЯВА {i}:\nНазвание: {it.get('title', '')}\nСуть: {text}")
    return await _ask(_SYSTEM_TOP3, "\n\n".join(blocks))
