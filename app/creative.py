def build_creative_prompt(fact: dict, fmt: dict, recent_openers: list[str]) -> str:
    parts = []
    parts.append(f"ФАКТ (только это правда, ничего не выдумывай):")
    parts.append(f"- Что за халява: {fact.get('title', '')}")
    parts.append(f"- Что конкретно дают: {fact.get('what') or fact.get('description') or '—'}")
    parts.append(f"- Сервис: {fact.get('source') or '—'}")
    parts.append(f"- Категория: {fact.get('category') or '—'}")
    parts.append(f"- Дата: {fact.get('date') or 'неизвестна'}")
    if fact.get("link_type") == "offer":
        parts.append("- ТИП ССЫЛКИ: прямая — ведёт на сам сервис/страницу акции. "
                     "Можно смело звать «переходи и забирай».")
    else:
        parts.append("- ТИП ССЫЛКИ: НОВОСТЬ/статья про халяву (НЕ сам сервис). "
                     "НЕ пиши «зайди по ссылке и регистрируйся/пользуйся». Честно: по ссылке — "
                     "подробности и источник; забирать халяву читатель идёт в сам сервис "
                     f"({fact.get('source') or 'сервис из факта'}).")
    parts.append("")
    parts.append(f"ФОРМАТ ЭТОГО ПОСТА — «{fmt['name']}»:")
    parts.append(fmt["guide"])
    parts.append("")
    if recent_openers:
        parts.append("НЕ повторяй зачины и структуру этих недавних постов канала:")
        for o in recent_openers:
            parts.append(f"  ⨯ {o}")
        parts.append("")
    parts.append(
        "Напиши тело поста в выбранном формате. Эмодзи — уместно, но без перебора. "
        "Ссылку и подпись канала НЕ добавляй. Ответ — строго JSON {\"text\": \"...\"}."
    )
    return "\n".join(parts)


def _extract_text(raw: str) -> str:
    """Достаём поле text из JSON-ответа модели; при неудаче — чистим как plain-текст."""
    raw = (raw or "").strip()
    m = re.search(r"```(?:json)?\s*(.*?)```", raw, re.S)
    if m:
        raw = m.group(1).strip()
    s, e = raw.find("{"), raw.rfind("}")
    if s != -1 and e != -1 and e > s:
        blob = raw[s:e + 1]
        # Модель при высокой температуре часто кладёт в JSON-строку СЫРЫЕ переводы
        # строк — это невалидный JSON, парсер падал, и в канал улетал голый
        # {"text": ...} со скобками. Поэтому пробуем: как есть → с ремонтом \n и \t.
        repaired = blob.replace("\r", "").replace("\n", "\\n").replace("\t", "\\t")
        for candidate in (blob, repaired):
            try:
                obj = json.loads(candidate)
                txt = (obj.get("text") or "").strip()
                if txt:
                    return txt
            except Exception:
                continue
        # Последняя страховка: выдираем содержимое "text": "..." руками,
        # чтобы обёртка ни при каком раскладе не ушла в канал.
        m2 = re.search(r'"text"\s*:\s*"(.*?)"\s*}\s*$', blob, re.S)
        if m2:
            txt = m2.group(1).replace('\\"', '"').replace("\\n", "\n").strip()
            if txt:
                return txt
    # запасной вариант: модель вернула чистый текст без JSON-обёртки
    return raw


def _opener(text: str, n: int = 70) -> str:
    """Короткий «зачин» поста для анти-повтора: первая строка без тегов."""
    plain = re.sub(r"<[^>]+>", "", text or "").strip()
    first = plain.splitlines()[0] if plain.splitlines() else plain
    return first[:n]


async def write_post(fact: dict, fmt: dict, recent_openers: list[str]) -> dict:
    """Пишем один пост. Возвращает факт, дополненный полями text_body и format.
    При ошибке модели — откат к сухому тексту из факта, чтобы пост всё равно вышел."""
    prompt = build_creative_prompt(fact, fmt, recent_openers)
    await bus.log(f"      ✍️ [Креативщик] формат «{fmt['name']}», temp={config.CREATIVE_TEMPERATURE}")
    try:
        raw = await clients.deepseek(
            [
                {"role": "system", "content": CREATIVE_SYSTEM},
                {"role": "user", "content": prompt},
            ],
            temperature=config.CREATIVE_TEMPERATURE,
            model=config.CREATIVE_MODEL,
        )
        text = _extract_text(raw)
    except Exception as e:
        await bus.log(f"      ✍️ [Креативщик] ошибка ({type(e).__name__}) — откат к сухому тексту", "warn")
        text = ""

    if not text:
        # аварийный откат: собираем простой пост из факта
        title = fact.get("title", "").strip()
        what = (fact.get("what") or fact.get("description") or "").strip()
        text = f"<b>{title}</b>\n\n{what}".strip()

    out = dict(fact)
    out["text_body"] = text
    out["format"] = fmt["key"]
    return out


def recent_openers(lookback: int) -> list[str]:
    """Зачины последних постов из истории — для анти-повтора."""
    hist = store.load()[-lookback:]
    openers = []
    for it in hist:
        body = it.get("text") or it.get("title") or ""
        op = _opener(body)
        if op:
            openers.append(op)
    return openers


def recent_formats(lookback: int) -> list[str]:
    """Форматы последних постов — чтобы не повторять их в новой пачке."""
    hist = store.load()[-lookback:]
    return [it.get("format") for it in hist if it.get("format")]
