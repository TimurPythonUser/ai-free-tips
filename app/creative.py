def pick_formats(n: int, recent_formats: list[str]) -> list[dict]:
    """Выбираем n форматов без повторов внутри пачки, по возможности избегая недавних.
    Приоритет — форматы, которых давно не было; недавние идут в резерв."""
    recent = set(recent_formats or [])
    fresh = [f for f in FORMATS if f["key"] not in recent]
    stale = [f for f in FORMATS if f["key"] in recent]
    random.shuffle(fresh)
    random.shuffle(stale)
    pool = fresh + stale                      # сначала давно не использованные
    if n <= len(pool):
        return pool[:n]
    # постов больше, чем форматов — добираем случайными (повтор допустим)
    extra = [random.choice(FORMATS) for _ in range(n - len(pool))]
    return pool + extra


